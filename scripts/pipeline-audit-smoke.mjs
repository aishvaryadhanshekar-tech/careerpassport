import { expect } from '@playwright/test';
export async function runPipelineAudit(page){
 const close=async()=>{const button=page.getByRole('button',{name:'Close detail panel',exact:true});if(await button.count())await button.click();};
 await page.setViewportSize({width:1512,height:982});await close();
 const positions=()=>page.locator('.react-flow__node').evaluateAll(nodes=>Object.fromEntries(nodes.map(n=>[n.getAttribute('data-id'),n.style.transform])));
 const before=await positions();
 const links=await page.locator('.react-flow__edge').count();
 await page.getByRole('button',{name:'Stage overview',exact:true}).click();
 await expect(page.locator('.fn-trip')).toHaveCount(0);
 await expect(page.locator('.fn-stage')).not.toHaveCount(0);
 await expect(page.locator('.react-flow__node[data-id="offered"]')).toBeInViewport({ratio:0.8});
 await page.screenshot({path:'/tmp/pipeline-compact-overview.png',fullPage:true});
 await page.getByRole('button',{name:'Detailed canvas',exact:true}).click();
 await expect(async()=>expect(await positions()).toEqual(before)).toPass();
 await expect(page.locator('.react-flow__edge')).toHaveCount(links);
 await page.getByRole('button',{name:'Add block after Applied',exact:true}).first().evaluate(el=>el.click());
 await expect(page.getByLabel('Block placement')).toHaveValue('applied');
 await page.getByLabel('Block type').selectOption('round');
 await page.getByLabel('Block name').fill('Reference conversation');
 await page.getByRole('button',{name:'Add to canvas',exact:false}).click();
 await expect(page.locator('.react-flow__node').filter({hasText:'Reference conversation'})).toHaveCount(1);
 await page.locator('.funnel-header-actions').getByRole('button',{name:/Publish/}).click();
 const comparison=page.getByRole('region',{name:'Changes since publication'});
 await expect(comparison).toContainText('Reference conversation');
 await expect(comparison).toContainText('Added');
 await page.screenshot({path:'/tmp/pipeline-publish-comparison.png',fullPage:true});
 await close();await page.getByRole('tab',{name:'Trips',exact:true}).click();
 const back=page.getByRole('button',{name:'← Trip library',exact:true});if(await back.count())await back.click();
 await page.getByLabel('Search trips',{exact:true}).fill('does-not-exist');
 await expect(page.getByText('No trips match these filters.')).toBeVisible();
 await page.getByLabel('Search trips',{exact:true}).fill('');
 await page.getByLabel('Library status').selectOption('published');
 await expect(page.locator('.pipeline-trip-library-row')).not.toHaveCount(0);
 for(const row of await page.locator('.pipeline-trip-library-row').all())await expect(row).toContainText('Published');
 await page.getByRole('button',{name:'Trip components & responses ↗',exact:true}).click();
 await expect(page.getByLabel('Search component trips')).toBeVisible();
 await page.getByRole('button',{name:'＋ Generate AI trip',exact:true}).click();
 await expect(page.getByLabel('Trip title',{exact:true})).toBeVisible();
 await expect(page.getByRole('tab',{name:'Edit',exact:true})).toBeVisible();
 await expect(page.getByRole('tab',{name:'Preview',exact:true})).toBeVisible();
 await page.setViewportSize({width:390,height:982});
 await page.screenshot({path:'/tmp/pipeline-component-trip.png',fullPage:true});
 await close();await page.setViewportSize({width:1512,height:982});
 console.log('PASS: compact overview preserves positions/links, inline insertion placement, live/draft comparison, library filters and component Trip navigation.');
}
